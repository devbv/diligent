function fixtureResult(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>) {
  const result = value.turns[0]!.messages.find(
    (message) => message.role === "tool_result" && message.toolName === "retrieve_archived_record",
  );
  if (!result || result.role !== "tool_result") throw new Error("Missing fixture result.");
  return result;
}

function readResult(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>) {
  const result = value.turns[0]!.messages.find(
    (message) => message.role === "tool_result" && message.toolName === "read",
  );
  if (!result || result.role !== "tool_result") throw new Error("Missing read result.");
  return result;
}

function mutateTruncatedSize(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>): void {
  const metadata = fixtureResult(value).metadata as { truncatedFrom: { bytes: number } };
  metadata.truncatedFrom.bytes += 1;
}

function removeFixtureResult(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>): void {
  const result = fixtureResult(value);
  value.turns[0]!.messages.splice(value.turns[0]!.messages.indexOf(result), 1);
}

function duplicateFixtureResult(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>): void {
  const result = fixtureResult(value);
  value.turns[0]!.messages.splice(value.turns[0]!.messages.indexOf(result), 0, structuredClone(result));
}

